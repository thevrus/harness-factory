#!/usr/bin/env python3
"""Regenerate docs/checks.md from the audit's check registry.

Usage: python3 tools/gen_check_docs.py
The registry is the source of truth; never edit docs/checks.md by hand.
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "skills", "harness-factory", "scripts"))

from hf_checks import load_checks  # noqa: E402
from hf_checks.registry import REQUIRED, RUNG_NAMES  # noqa: E402

RUNG_GOALS = {
    1: "The agent can find its way and knows the real commands.",
    2: "\"Done\" can be proven by a command.",
    3: "Mistakes stay small and visible.",
    4: "One unattended automation that can only comment or label.",
    5: "Issue to draft pull request, measured.",
}


def cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def main() -> int:
    checks = load_checks()
    out = [
        "# Checks",
        "",
        "<!-- Generated by tools/gen_check_docs.py. Do not edit by hand. -->",
        "",
        "Every check the audit runs, grouped by rung. %d checks in total." % len(checks),
        "",
        "- **Required** checks decide the rung. A rung counts only when every required "
        "check on it and on every rung below passes.",
        "- **Recommended** checks are reported and never block a rung.",
        "- A check that could not be measured (for example, one that needs `--run`) "
        "blocks a rung the same way a failing one does.",
        "",
        "For one check in the terminal: "
        "`python3 skills/harness-factory/scripts/hf_audit.py --explain <ID>`",
        "",
    ]
    for rung in sorted(RUNG_GOALS):
        name, goal = RUNG_NAMES[rung], RUNG_GOALS[rung]
        mine = [c for c in checks if c.rung == rung]
        req = sum(1 for c in mine if c.severity == REQUIRED)
        out += [
            "## Rung %d: %s" % (rung, name),
            "",
            "%s %d required, %d recommended." % (goal, req, len(mine) - req),
            "",
        ]
        for c in mine:
            out += [
                "### `%s`" % c.id,
                "",
                "**%s** (%s)" % (c.title, c.severity),
                "",
                "| | |",
                "|---|---|",
                "| Why it matters | %s |" % cell(c.why),
                "| How it is detected | %s |" % cell(c.how),
                "| Fix | %s |" % cell(c.fix),
                "",
            ]
    path = os.path.join(ROOT, "docs", "checks.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out).rstrip() + "\n")
    print("wrote %s (%d checks)" % (path, len(checks)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
